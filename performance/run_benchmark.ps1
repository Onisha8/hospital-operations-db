<#
.SYNOPSIS
    Before/after index benchmark for HospitalOps.

.DESCRIPTION
    1. Drops all tuning indexes (performance/drop_tuning_indexes.sql)
    2. Runs the workload       -> phase "before"
    3. Creates tuning indexes  (sql/09_performance_indexes.sql)
    4. Runs the workload again -> phase "after"
    5. Exports each query's cached execution plan to performance/plans/<phase>/Wnn.sqlplan
       (open these in SSMS to view the graphical plan)
    6. Writes the comparison table to performance/results.md

    Run after a full build (.\run_sql.ps1). Leaves the database WITH the tuning indexes.

.EXAMPLE
    .\performance\run_benchmark.ps1
#>
[CmdletBinding()]
param([string] $Server = 'localhost')

$ErrorActionPreference = 'Stop'
$root   = Split-Path $PSScriptRoot -Parent
$runner = Join-Path $root 'run_sql.ps1'
$perf   = $PSScriptRoot

function Invoke-Step([string[]] $files, [hashtable] $vars = @{}) {
    & $runner -Server $Server -Files $files -Variables $vars
    if ($LASTEXITCODE -ne 0) { throw "Step failed: $($files -join ', ')" }
}

Write-Host '==> Dropping tuning indexes, benchmarking BEFORE' -ForegroundColor Cyan
Invoke-Step @("$perf\drop_tuning_indexes.sql", "$perf\benchmark.sql") @{ Phase = 'before' }

Write-Host '==> Creating tuning indexes, benchmarking AFTER' -ForegroundColor Cyan
Invoke-Step @("$root\sql\09_performance_indexes.sql", "$perf\benchmark.sql") @{ Phase = 'after' }

$conn = New-Object System.Data.SqlClient.SqlConnection "Server=$Server;Database=HospitalOps;Integrated Security=true;TrustServerCertificate=true"
$conn.Open()
try {
    $q = @'
WITH latest AS (
    SELECT Phase, MAX(RunID) AS RunID FROM perf.BenchmarkRun GROUP BY Phase
),
b AS (SELECT r.* FROM perf.BenchmarkResult r JOIN latest l ON l.RunID = r.RunID AND l.Phase = 'before'),
a AS (SELECT r.* FROM perf.BenchmarkResult r JOIN latest l ON l.RunID = r.RunID AND l.Phase = 'after'),
cal AS (SELECT b.AvgLogicalReads AS BeforeOverhead, a.AvgLogicalReads AS AfterOverhead
        FROM b JOIN a ON a.Code = b.Code WHERE b.Code = 'W00')
SELECT w.Code, w.Area, w.Description,
       b.AvgLogicalReads AS ReadsBefore, a.AvgLogicalReads AS ReadsAfter,
       -- net of the SELECT INTO #sink overhead (not applied to W00 itself or W14, which has no INTO)
       CASE WHEN w.SqlText LIKE '%INTO #sink%' AND w.Code <> 'W00' THEN b.AvgLogicalReads - cal.BeforeOverhead END AS NetReadsBefore,
       CASE WHEN w.SqlText LIKE '%INTO #sink%' AND w.Code <> 'W00' THEN a.AvgLogicalReads - cal.AfterOverhead  END AS NetReadsAfter,
       b.AvgElapsedMs AS MsBefore, a.AvgElapsedMs AS MsAfter,
       b.AvgCpuMs AS CpuBefore, a.AvgCpuMs AS CpuAfter,
       b.PlanXml AS PlanBefore, a.PlanXml AS PlanAfter
FROM perf.Workload w
JOIN b ON b.Code = w.Code
JOIN a ON a.Code = w.Code
CROSS JOIN cal
ORDER BY w.Code;
'@
    $cmd = $conn.CreateCommand(); $cmd.CommandText = $q
    $t = New-Object System.Data.DataTable
    $t.Load($cmd.ExecuteReader())

    foreach ($phase in 'before', 'after') { New-Item -ItemType Directory -Force (Join-Path $perf "plans\$phase") | Out-Null }

    # Invariant culture: 180,597 everywhere (not the machine's locale grouping, e.g. 1,80,597)
    $inv = [System.Globalization.CultureInfo]::InvariantCulture
    $fmtReads = { param($v) if ($v -is [DBNull]) { '-' } else { ([int64]$v).ToString('N0', $inv) } }
    $fmtMs    = { param($v) if ([decimal]$v -lt 1) { '<1' } else { ([decimal]$v).ToString('N0', $inv) } }
    $md = New-Object System.Collections.Generic.List[string]
    $md.Add('# Benchmark results')
    $md.Add('')
    $md.Add("Generated by ``performance/run_benchmark.ps1`` on $(Get-Date -Format 'yyyy-MM-dd'). Warm cache, average of 5 runs per query after 1 warm-up run. Logical reads are the stable metric; times under ~1 ms are at timer resolution. SQL Server 2022 Developer, 8 cores. Data: ~1.39M rows.")
    $md.Add('')
    $md.Add('| Query | Area | What it does | Reads before | Reads after | Reads change | ms before | ms after |')
    $md.Add('|---|---|---|---:|---:|---:|---:|---:|')
    foreach ($row in $t.Rows) {
        $code = $row.Code
        foreach ($phase in 'before', 'after') {
            $planCol = if ($phase -eq 'before') { 'PlanBefore' } else { 'PlanAfter' }
            if ($row[$planCol] -isnot [DBNull]) {
                [System.IO.File]::WriteAllText((Join-Path $perf "plans\$phase\$code.sqlplan"), [string]$row[$planCol], [System.Text.Encoding]::UTF8)
            }
        }
        if ($code -eq 'W00') { continue }
        $rb = if ($row.NetReadsBefore -is [DBNull]) { $row.ReadsBefore } else { $row.NetReadsBefore }
        $ra = if ($row.NetReadsAfter  -is [DBNull]) { $row.ReadsAfter  } else { $row.NetReadsAfter  }
        $change = if ([double]$ra -le 0) { 'n/a' }
                  elseif ([double]$rb / [double]$ra -ge 1.5) { ([double]$rb / [double]$ra).ToString('N0', $inv) + 'x fewer' }
                  elseif ([double]$ra / [double]$rb -ge 1.5)  { ([double]$ra / [double]$rb).ToString('N1', $inv) + 'x more' }
                  elseif ([double]$ra / [double]$rb -ge 1.05) { ([double]$ra / [double]$rb * 100 - 100).ToString('N0', $inv) + '% more' }
                  else { 'no change' }
        $md.Add("| $code | $($row.Area) | $($row.Description) | $(& $fmtReads $rb) | $(& $fmtReads $ra) | $change | $(& $fmtMs $row.MsBefore) | $(& $fmtMs $row.MsAfter) |")
    }
    $md.Add('')
    $md.Add('Reads for W01-W13 are net of the fixed `SELECT ... INTO #sink` overhead measured by calibration query W00. Execution plans: `performance/plans/before|after/Wnn.sqlplan` (open in SSMS).')
    [System.IO.File]::WriteAllLines((Join-Path $perf 'results.md'), $md, (New-Object System.Text.UTF8Encoding $false))

    $t | Select-Object Code, NetReadsBefore, NetReadsAfter, ReadsBefore, ReadsAfter, MsBefore, MsAfter | Format-Table -AutoSize | Out-String -Width 200 | Write-Host
    Write-Host "Wrote performance\results.md and $($t.Rows.Count * 2) plan files." -ForegroundColor Green
}
finally { $conn.Close() }
